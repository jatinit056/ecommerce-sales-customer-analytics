"""Run every query in sql/analysis_queries.sql and save each result as a CSV file.

Each query in the .sql file starts with a comment line like:  -- Q07: <question>
The script runs the queries one by one with `psql` (so PostgreSQL's psql must be on PATH)
and writes sql/results/Q07.csv etc. plus sql/results/summary.md with the first rows of each result.

Usage (from the project root):
    python scripts/run_sql_queries.py --db olist_db
    # connection settings come from the usual PG* environment variables (PGHOST, PGPORT, PGUSER, PGPASSWORD)
"""
import argparse
import csv
import io
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def split_queries(sql_text):
    """Return a list of (query_id, question, sql) using the '-- Qnn:' markers."""
    header_end = sql_text.find("-- Q01:")
    preamble = sql_text[:header_end]
    search_path = re.search(r"SET search_path TO [^;]+;", preamble)
    prefix = search_path.group(0) + "\n" if search_path else ""
    parts = re.split(r"(?m)^-- (Q\d{2}): ", sql_text[header_end:])
    queries = []
    for i in range(1, len(parts), 2):
        qid, body = parts[i], parts[i + 1]
        question = body.splitlines()[0].strip()
        # drop section banner comments that follow the query
        body = re.split(r"(?m)^-{20,}", body)[0]
        queries.append((qid, question, prefix + "-- " + body.strip() + "\n"))
    return queries


def run(sql, db):
    result = subprocess.run(["psql", "-X", "-q", "-v", "ON_ERROR_STOP=1", "--csv", "-d", db],
                            input=sql, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(result.stderr)
    return result.stdout


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--db", required=True, help="database name")
    parser.add_argument("--sql", default=str(ROOT / "sql" / "analysis_queries.sql"))
    parser.add_argument("--out", default=str(ROOT / "sql" / "results"))
    parser.add_argument("--preview-rows", type=int, default=8)
    args = parser.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    queries = split_queries(Path(args.sql).read_text(encoding="utf-8"))
    summary = ["# SQL query results", "",
               "Generated by `scripts/run_sql_queries.py` from `sql/analysis_queries.sql` "
               "(PostgreSQL). Full results are in the CSV files next to this file.", ""]
    failures = 0
    for qid, question, sql in queries:
        try:
            text = run(sql, args.db)
        except RuntimeError as err:
            failures += 1
            print(f"{qid} FAILED: {err}", file=sys.stderr)
            continue
        (out / f"{qid}.csv").write_text(text, encoding="utf-8")
        rows = list(csv.reader(io.StringIO(text)))
        header, data = rows[0], rows[1:]
        print(f"{qid}: {len(data)} rows  - {question}")
        summary += [f"## {qid} — {question}", "", f"Rows returned: {len(data)}", "",
                    "| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
        summary += ["| " + " | ".join(r) + " |" for r in data[:args.preview_rows]]
        if len(data) > args.preview_rows:
            summary.append(f"| … {len(data) - args.preview_rows} more rows | " + " | " * (len(header) - 1))
        summary.append("")
    (out / "summary.md").write_text("\n".join(summary), encoding="utf-8")
    print(f"\n{len(queries) - failures}/{len(queries)} queries ran successfully. Results in {out}")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
